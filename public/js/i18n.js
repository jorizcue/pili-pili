let _lang = (typeof localStorage !== 'undefined' && localStorage.getItem('pochaset_lang')) || 'es';

/** Translate a key, optionally interpolating {var} placeholders */
window.t = function(key, vars) {
  const dict = TRANSLATIONS[_lang] || TRANSLATIONS.es;
  const str  = dict[key] !== undefined ? dict[key] : (TRANSLATIONS.es[key] || key);
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
};

window.setLang = function(lang) {
  if (!TRANSLATIONS[lang]) return;
  _lang = lang;
  if (typeof localStorage !== 'undefined') localStorage.setItem('pochaset_lang', lang);
  // Update all static data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = window.t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = window.t(el.dataset.i18nHtml);
  });
  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = window.t(el.dataset.i18nPlaceholder);
  });
  // Update language selector
  const sel = document.getElementById('langSelect');
  if (sel) sel.value = lang;
  // Notify listeners
  if (typeof window.onLangChange === 'function') window.onLangChange(lang);
};

window.getLang = () => _lang;

